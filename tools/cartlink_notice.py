# Writes NOTICE-CARTLINK.md: which upstream RetroArch files Cartlink
# changed, added or removed, from `git diff --name-status <base>` (the
# working tree, so run it after the last change; new files must be
# tracked or added with `git add -N`).
#
# Usage: tools/cartlink_notice.py [<base commit>]   (default 69a4f0e)

import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = sys.argv[1] if len(sys.argv) > 1 else "69a4f0e"
MBED = "deps/mbedtls/"
OWN_DOCS = {"NOTICE-CARTLINK.md"}
# Upstream files Cartlink replaced as a whole with its own text.
REPLACED_PREFIX = (".github/", "README.md", "SECURITY.md")


def diff():
    out = subprocess.check_output(
        ["git", "-C", ROOT, "diff", "--name-status", "--no-renames", BASE],
        text=True)
    rows = []
    for line in out.splitlines():
        status, path = line.split("\t", 1)
        if path not in OWN_DOCS:
            rows.append((status[0], path))
    return rows


def main():
    rows = diff()
    mod = sorted(p for s, p in rows if s == "M" and not p.startswith(MBED)
                 and not p.startswith(REPLACED_PREFIX))
    rep = sorted(p for s, p in rows if s == "M" and p.startswith(REPLACED_PREFIX))
    add = sorted(p for s, p in rows if s == "A" and not p.startswith(MBED))
    rem = sorted(p for s, p in rows if s == "D" and not p.startswith(MBED))
    mbed = [p for s, p in rows if p.startswith(MBED)]
    out = []
    w = out.append
    w("# Cartlink notice")
    w("")
    w("Cartlink is a modified version of **RetroArch v1.22.2** (upstream")
    w("commit `%s`, https://github.com/libretro/RetroArch), modified by" % BASE)
    w("Cartlink contributors since November 2026. It is not made, endorsed")
    w("or supported by the libretro team.")
    w("")
    w("RetroArch and Cartlink are free software under the GNU General Public")
    w("License, version 3 or (at your option) any later version; see")
    w("[COPYING](COPYING). Files from `libretro-common` keep their own")
    w("MIT-style licence headers; bundled libraries under `deps/` keep their")
    w("own licences.")
    w("")
    w("Each upstream file listed below as modified has the line")
    w("\"Modified by Cartlink contributors, 2026\" near the top. Each new")
    w("file carries \"Copyright (C) 2026 Cartlink contributors\" and the GPL v3")
    w("or later notice (except small data files such as icons and the")
    w("desktop entry).")
    w("")
    w("This list is generated by `tools/cartlink_notice.py` from")
    w("`git diff --name-status %s`." % BASE)
    w("")
    w("## Modified upstream files (%d)" % len(mod))
    w("")
    for p in mod:
        w("- `%s`" % p)
    w("")
    w("## Upstream files replaced with Cartlink's own text (%d)" % len(rep))
    w("")
    for p in rep:
        w("- `%s`" % p)
    w("")
    w("## New files (%d)" % len(add))
    w("")
    for p in add:
        w("- `%s`" % p)
    w("")
    w("## Removed upstream files (%d)" % len(rem))
    w("")
    w("RetroArch's CI workflows, issue templates, funding file, libretro")
    w("desktop/metainfo files and libretro's store listings and packaging")
    w("metadata (fastlane, Google Play texts, App Store upload settings,")
    w("Debian packaging) were removed or replaced, because Cartlink is a")
    w("separate project.")
    w("")
    for p in rem:
        w("- `%s`" % p)
    w("")
    w("## Bundled mbedTLS (`deps/mbedtls`)")
    w("")
    w("RetroArch's mbedTLS 2.6.0 copy was replaced with the unmodified Mbed TLS")
    w("2.28.10 release (Apache-2.0, `deps/mbedtls/LICENSE`) except for")
    w("`deps/mbedtls/mbedtls/config.h` (Cartlink build settings, marked")
    w("\"Modified by Cartlink contributors, 2026\") and the Cartlink file")
    w("`deps/mbedtls/sources.mk`. Source, SHA-256 and the exact config")
    w("changes: `deps/mbedtls/CARTLINK-VERSION.txt`. %d files under" % len(mbed))
    w("`deps/mbedtls/` differ from the upstream RetroArch commit.")
    w("")
    with open(os.path.join(ROOT, "NOTICE-CARTLINK.md"), "w") as f:
        f.write("\n".join(out))
    print("NOTICE-CARTLINK.md: %d modified, %d replaced, %d new, %d removed,"
          " %d mbedTLS" % (len(mod), len(rep), len(add), len(rem), len(mbed)))


if __name__ == "__main__":
    main()
